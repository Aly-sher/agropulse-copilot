"""Strict data contracts for AI-generated advice and chemical safety."""

from pydantic import BaseModel, Field, field_validator
from typing import List, Optional

class ActionItem(BaseModel):
    """A single actionable step for the farmer."""
    text: str
    source_ids: List[str] = Field(default_factory=list, description="IDs of the knowledge cards used.")

class ActionWindow(BaseModel):
    """Deterministic weather and irrigation constraints."""
    can_spray_today: bool
    irrigation_due_hours: int
    wind_warning: bool

class Advice(BaseModel):
    """
    The final, grounded advice generated by the LLM.
    Strictly validated to prevent hallucinations and unsafe chemical recommendations.
    """
    summary: str
    confidence_statement: str
    do_today: List[ActionItem]
    monitor: List[ActionItem]
    escalate_if: List[ActionItem]
    chemical_options: List[str] = Field(default_factory=list)
    action_window: ActionWindow

    @field_validator("chemical_options")
    @classmethod
    def validate_chemical_safety(cls, v: List[str]) -> List[str]:
        """
        Code-Rendered Chemical Safety Guardrail.
        Fail-safe approach: Only allows pre-approved, safe chemical keywords.
        Blocks any hallucinated or unverified chemical names.
        """
        # This is our "Safe Registry". In production, this comes from a secure SQL DB.
        approved_chemicals = [
            "propiconazole", "tebuconazole", "mancozeb", 
            "urea", "dap", "potassium chloride"
        ]
        
        safe_options = []
        for chem in v:
            chem_lower = chem.lower()
            # Check if the LLM's output contains an approved chemical keyword
            if any(approved in chem_lower for approved in approved_chemicals):
                safe_options.append(chem)
            else:
                # FAIL-SAFE: If it's an unknown chemical, block it entirely.
                raise ValueError(f"Unsafe or unverified chemical recommendation blocked: '{chem}'.")
        
        return safe_options